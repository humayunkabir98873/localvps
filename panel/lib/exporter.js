const isNode = (site) => site.type === 'node';
// Port the Node app listens on behind nginx on the VPS.
const remoteAppPort = (site) => site.appPort || 3000;

// ---------- bundle ----------
function linuxNginxConf(site) {
  const extra = site.extraNginx ? `\n    # --- extra directives from local site ---\n    ${site.extraNginx.split('\n').join('\n    ')}\n` : '';
  if (isNode(site)) {
    return `# Generated by LocalVPS export for Node site "${site.name}"
server {
    listen 80;
    listen [::]:80;
    server_name __DOMAIN__;
    client_max_body_size 256m;

    access_log /var/log/nginx/${site.name}.access.log;
    error_log  /var/log/nginx/${site.name}.error.log;

    location / {
        proxy_pass http://127.0.0.1:${remoteAppPort(site)};
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_read_timeout 300;
    }
${extra}}
`;
  }
  const webroot = site.webroot && site.webroot !== '.' ? `/${site.webroot}` : '';
  return `# Generated by LocalVPS export for "${site.name}"
server {
    listen 80;
    listen [::]:80;
    server_name __DOMAIN__;
    root /var/www/${site.name}${webroot};
    index index.php index.html index.htm;
    charset utf-8;
    client_max_body_size 256m;

    access_log /var/log/nginx/${site.name}.access.log;
    error_log  /var/log/nginx/${site.name}.error.log;

    location / {
        try_files $uri $uri/ /index.php?$query_string;
    }

    location ~ \\.php$ {
        try_files $uri =404;
        include fastcgi_params;
        fastcgi_pass unix:/run/php/php${site.php}-fpm.sock;
        fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
        fastcgi_read_timeout 300;
    }

    location ~ /\\.(?!well-known) {
        deny all;
    }
${extra}}
`;
}

function phpInstallBlock(php) {
  return `
if ! apt-cache show "php${php}-fpm" >/dev/null 2>&1; then
  log "Adding PHP repository for PHP ${php}"
  if [[ "$ID" == "ubuntu" ]]; then
    apt-get install -y software-properties-common
    add-apt-repository -y ppa:ondrej/php
  else
    curl -fsSL https://packages.sury.org/php/apt.gpg -o /usr/share/keyrings/sury-php.gpg
    echo "deb [signed-by=/usr/share/keyrings/sury-php.gpg] https://packages.sury.org/php/ $(lsb_release -sc) main" > /etc/apt/sources.list.d/sury-php.list
  fi
  apt-get update -y
fi

log "Installing PHP ${php}"
PKGS=(fpm cli mysql curl gd intl mbstring xml zip bcmath sqlite3)
apt-get install -y $(printf "php${php}-%s " "\${PKGS[@]}")
# opcache is a separate package up to PHP 8.4 and built in from 8.5
apt-get install -y "php${php}-opcache" 2>/dev/null || true
systemctl enable --now "php${php}-fpm"
`;
}

function nodeInstallBlock() {
  return `
NODE_MAJOR=22
if ! command -v node >/dev/null || [[ "$(node -p 'process.versions.node.split(".")[0]')" -lt 20 ]]; then
  log "Installing Node.js $NODE_MAJOR LTS (NodeSource)"
  curl -fsSL "https://deb.nodesource.com/setup_\${NODE_MAJOR}.x" | bash -
  apt-get install -y nodejs
fi
log "Node $(node -v), npm $(npm -v)"
`;
}

function dbBlock(site) {
  const db = site.db;
  if (!db) return '';
  return `
log "Creating database ${db.name}"
# Same name, user and password as on the local machine, so the app config works unchanged.
mariadb <<SQL
CREATE DATABASE IF NOT EXISTS \\\`${db.name}\\\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '${db.user}'@'localhost' IDENTIFIED BY '${db.password}';
CREATE USER IF NOT EXISTS '${db.user}'@'127.0.0.1' IDENTIFIED BY '${db.password}';
GRANT ALL PRIVILEGES ON \\\`${db.name}\\\`.* TO '${db.user}'@'localhost';
GRANT ALL PRIVILEGES ON \\\`${db.name}\\\`.* TO '${db.user}'@'127.0.0.1';
FLUSH PRIVILEGES;
SQL
if [[ -f "$HERE/db.sql" ]]; then
  log "Importing database dump"
  mariadb "${db.name}" < "$HERE/db.sql"
fi
${site.template === 'blank' ? `cat > "/var/www/$SITE/db.local.php" <<'PHP'
<?php
return ['host' => '127.0.0.1', 'port' => 3306, 'name' => '${db.name}', 'user' => '${db.user}', 'password' => '${db.password}'];
PHP
chown www-data:www-data "/var/www/$SITE/db.local.php"; chmod 640 "/var/www/$SITE/db.local.php"
` : ''}`;
}

function phpAppFixups(meta) {
  return `
WPCONF="$(find "/var/www/$SITE" -maxdepth 2 -name wp-config.php | head -n1 || true)"
if [[ -n "$WPCONF" ]]; then
  log "WordPress detected: fixing DB host and URLs"
  sed -i "s/define( *'DB_HOST', *'[^']*' *);/define( 'DB_HOST', 'localhost' );/" "$WPCONF"
  if ! command -v wp >/dev/null; then
    curl -fsSL -o /usr/local/bin/wp https://raw.githubusercontent.com/wp-cli/builds/gh-pages/phar/wp-cli.phar
    chmod +x /usr/local/bin/wp
  fi
  sudo -u www-data wp --path="$(dirname "$WPCONF")" search-replace "${meta.localUrl}" "$SCHEME://$DOMAIN" --all-tables --skip-columns=guid || true
fi

if [[ -f "/var/www/$SITE/artisan" ]]; then
  log "Laravel detected: production .env, migrations, caches"
  ENVF="/var/www/$SITE/.env"
  set_env() { if grep -qE "^#?\\s*$1=" "$ENVF"; then sed -i -E "s|^#?\\s*$1=.*|$1=$2|" "$ENVF"; else echo "$1=$2" >> "$ENVF"; fi; }
  set_env APP_ENV production
  set_env APP_DEBUG false
  set_env APP_URL "$SCHEME://$DOMAIN"
  set_env DB_HOST 127.0.0.1
  set_env DB_PORT 3306
  chmod 640 "$ENVF"
  cd "/var/www/$SITE"
  sudo -u www-data php artisan migrate --force
  sudo -u www-data php artisan optimize
  cd "$HERE"
fi
`;
}

function nodeAppBlock(site) {
  const port = remoteAppPort(site);
  return `
log "Installing dependencies and building (npm ci && npm run build)"
NPM_HOME="/var/www/.npm-$SITE"
mkdir -p "$NPM_HOME" && chown www-data:www-data "$NPM_HOME"
cd "/var/www/$SITE"
sudo -u www-data env HOME="$NPM_HOME" NEXT_TELEMETRY_DISABLED=1 npm ci
sudo -u www-data env HOME="$NPM_HOME" NEXT_TELEMETRY_DISABLED=1 npm run build
cd "$HERE"

log "Creating systemd service $SITE.service (port ${port})"
cat > "/etc/systemd/system/$SITE.service" <<UNIT
[Unit]
Description=$SITE (Next.js)
After=network.target

[Service]
Type=simple
User=www-data
WorkingDirectory=/var/www/$SITE
Environment=NODE_ENV=production
Environment=PORT=${port}
Environment=HOME=$NPM_HOME
Environment=NEXT_TELEMETRY_DISABLED=1
ExecStart=$(command -v npm) start -- -p ${port} -H 127.0.0.1
Restart=always
RestartSec=3

[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload
systemctl enable "$SITE.service"
systemctl restart "$SITE.service"
`;
}

function provisionScript(site, meta) {
  const node = isNode(site);
  return `#!/usr/bin/env bash
# LocalVPS provisioning script for site "${site.name}" (${node ? 'Next.js' : `PHP ${site.php}`}).
# Tested targets: Ubuntu 22.04 / 24.04, Debian 12. Run as root or with sudo:
#   sudo bash provision.sh --domain example.com [--email you@example.com]
set -euo pipefail

SITE="${site.name}"
DOMAIN=""
EMAIL=""
HERE="$(cd "$(dirname "\${BASH_SOURCE[0]}")" && pwd)"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --domain) DOMAIN="$2"; shift 2 ;;
    --email)  EMAIL="$2";  shift 2 ;;
    *) echo "Unknown option $1"; exit 2 ;;
  esac
done
[[ -n "$DOMAIN" ]] || DOMAIN="$(hostname -I | awk '{print $1}')"
[[ $EUID -eq 0 ]] || { echo "Run as root (sudo bash provision.sh ...)"; exit 1; }
SCHEME=http; [[ -n "$EMAIL" ]] && SCHEME=https

log() { printf '\\n\\033[1;34m==> %s\\033[0m\\n' "$*"; }
export DEBIAN_FRONTEND=noninteractive

. /etc/os-release
log "Target: $PRETTY_NAME, domain: $DOMAIN"

log "Installing base packages"
apt-get update -y
apt-get install -y nginx curl ca-certificates lsb-release gnupg unzip${site.db ? ' mariadb-server' : ''}
systemctl enable --now nginx${site.db ? ' mariadb' : ''}
${node ? nodeInstallBlock() : phpInstallBlock(site.php)}
log "Deploying files to /var/www/$SITE"
mkdir -p "/var/www/$SITE"
tar -xzf "$HERE/site.tar.gz" -C "/var/www/$SITE"
rm -f "/var/www/$SITE/db.local.php"
chown -R www-data:www-data "/var/www/$SITE"
find "/var/www/$SITE" -type d -exec chmod 755 {} +
find "/var/www/$SITE" -type f -exec chmod 644 {} +
${dbBlock(site)}${node ? nodeAppBlock(site) : phpAppFixups(meta)}
log "Configuring nginx"
sed "s/__DOMAIN__/$DOMAIN/" "$HERE/nginx-site.conf" > "/etc/nginx/sites-available/$SITE.conf"
ln -sf "/etc/nginx/sites-available/$SITE.conf" "/etc/nginx/sites-enabled/$SITE.conf"
nginx -t
systemctl reload nginx

if command -v ufw >/dev/null && ufw status | grep -q active; then
  ufw allow 'Nginx Full' || true
fi

if [[ -n "$EMAIL" && ! "$DOMAIN" =~ ^[0-9.]+$ ]]; then
  log "Requesting a Let's Encrypt certificate"
  apt-get install -y certbot python3-certbot-nginx
  certbot --nginx -d "$DOMAIN" --non-interactive --agree-tos -m "$EMAIL" --redirect
fi

log "Done: $SCHEME://$DOMAIN/"
`;
}

export function exportSite({ name, includeDb = true }) {
  const site = findSite(name);
  return startJob('export', `Export ${name}`, async (ctx) => buildBundle(site, includeDb, ctx));
}

async function buildBundle(site, includeDb, ctx) {
  const stamp = new Date().toISOString().replace(/[:T]/g, '-').slice(0, 19);
  const id = `${site.name}-${stamp}`;
  const work = path.join(P.exports, id);
  fs.mkdirSync(work, { recursive: true });

  ctx.log(`Packing ${siteRoot(site)}`);
  // Node sites rebuild on the server: ship sources only, not Windows-built node_modules or .next.
  const excludes = isNode(site) ? ['--exclude', 'node_modules', '--exclude', '.next'] : [];
  await runOk(TAR, ['-czf', path.join(work, 'site.tar.gz'), ...excludes, '-C', siteRoot(site), '.']);

  if (includeDb && site.db) {
    if (!(await isRunning('mariadb'))) throw new Error('Start MariaDB to include the database');
    ctx.log(`Dumping database ${site.db.name}`);
    await dumpDatabase(site.db.name, path.join(work, 'db.sql'));
  }

  const port = getState().settings.httpPort;
  const localUrl = `http://${site.name}.localhost${port === 80 ? '' : `:${port}`}`;
  const meta = {
    site: site.name, type: site.type || 'php', template: site.template, php: site.php,
    appPort: isNode(site) ? remoteAppPort(site) : undefined,
    createdAt: new Date().toISOString(), localUrl, includesDb: Boolean(includeDb && site.db),
  };
  fs.writeFileSync(path.join(work, 'nginx-site.conf'), linuxNginxConf(site));
  fs.writeFileSync(path.join(work, 'provision.sh'), provisionScript(site, meta).replace(/\r\n/g, '\n'));
  fs.writeFileSync(path.join(work, 'localvps.json'), JSON.stringify(meta, null, 2));
  fs.writeFileSync(path.join(work, 'README.txt'), `LocalVPS export of "${site.name}" (${isNode(site) ? 'Next.js' : site.template === 'laravel' ? 'Laravel' : `PHP ${site.php}`})

1. Copy this folder (or the .tar.gz next to it) to your server, e.g.
   scp ${id}.tar.gz root@SERVER:/root/
2. On the server:
   mkdir ${id} && tar -xzf ${id}.tar.gz -C ${id} && cd ${id}
   sudo bash provision.sh --domain example.com --email you@example.com
   (omit --email to skip HTTPS; omit --domain to use the server IP)

Contents: site.tar.gz (files${isNode(site) ? ', without node_modules/.next — rebuilt on the server' : ''}), ${meta.includesDb ? 'db.sql (database dump), ' : ''}nginx-site.conf, provision.sh
`);

  const archive = path.join(P.exports, `${id}.tar.gz`);
  ctx.log('Creating bundle archive');
  await runOk(TAR, ['-czf', archive, '-C', work, '.']);
  const size = fs.statSync(archive).size;
  ctx.log(`Bundle ready: ${archive} (${fmtBytes(size)})`);
  return { id, archive, folder: work, size };
}

export function listExports() {
  if (!fs.existsSync(P.exports)) return [];
  return fs.readdirSync(P.exports)
    .filter((f) => f.endsWith('.tar.gz'))
    .map((f) => {
      const st = fs.statSync(path.join(P.exports, f));
      return { id: f.replace(/\.tar\.gz$/, ''), file: f, size: st.size, createdAt: st.mtime.toISOString() };
    })
    .sort((a, b) => b.createdAt.localeCompare(a.createdAt));
}

export function deleteExport(id) {
  if (!/^[a-z0-9-]+$/.test(id)) throw httpError(400, 'Invalid export id');
  fs.rmSync(path.join(P.exports, `${id}.tar.gz`), { force: true });
  fs.rmSync(path.join(P.exports, id), { recursive: true, force: true });
}

// ---------- servers & deploy ----------
export function listServers() { return getState().servers; }

export function saveServer({ id, name, host, port = 22, user = 'root', keyPath = '' }) {
  if (!/^[A-Za-z0-9.:_-]+$/.test(host || '')) throw httpError(400, 'Invalid host');
  if (!/^[a-z_][a-z0-9_-]*$/i.test(user)) throw httpError(400, 'Invalid user');
  if (keyPath && !fs.existsSync(keyPath)) throw httpError(400, `Key file not found: ${keyPath}`);
  const st = getState();
  const rec = { id: id || crypto.randomBytes(4).toString('hex'), name: name || host, host, port: Number(port) || 22, user, keyPath };
  const i = st.servers.findIndex((s) => s.id === rec.id);
  if (i >= 0) st.servers[i] = rec; else st.servers.push(rec);
  saveState();
  return rec;
}

export function deleteServer(id) {
  const st = getState();
  st.servers = st.servers.filter((s) => s.id !== id);
  saveState();
}

function sshBase(server) {
  // BatchMode: never prompt (the panel has no TTY); key or agent auth only.
  const opts = ['-o', 'BatchMode=yes', '-o', 'StrictHostKeyChecking=accept-new', '-o', 'ConnectTimeout=15'];
  if (server.keyPath) opts.push('-i', server.keyPath);
  return opts;
}

export async function testServer(id) {
  const server = getState().servers.find((s) => s.id === id);
  if (!server) throw httpError(404, 'Server not found');
  const r = await run(SSH, [...sshBase(server), '-p', String(server.port), `${server.user}@${server.host}`,
    'echo "connected as $(whoami) on $(hostname)"; . /etc/os-release && echo "$PRETTY_NAME"; (sudo -n true 2>/dev/null && echo "sudo: ok") || ([ "$(id -u)" = 0 ] && echo "sudo: root") || echo "sudo: needs password (deploy will fail)"']);
  return { ok: r.code === 0, output: (r.stdout + r.stderr).trim() };
}

export function deploySite({ name, serverId, domain = '', email = '', includeDb = true }) {
  const site = findSite(name);
  const server = getState().servers.find((s) => s.id === serverId);
  if (!server) throw httpError(404, 'Server not found');
  if (domain && !/^[A-Za-z0-9.-]+$/.test(domain)) throw httpError(400, 'Invalid domain');
  if (email && !/^[^\s@'"]+@[^\s@'"]+$/.test(email)) throw httpError(400, 'Invalid email');

  return startJob('deploy', `Deploy ${name} → ${server.name}`, async (ctx) => {
    const bundle = await buildBundle(site, includeDb, ctx);
    const remoteDir = `/tmp/localvps-${bundle.id}`;
    const target = `${server.user}@${server.host}`;
    const stream = { onData: (d) => ctx.log(d) };

    ctx.log(`Uploading bundle to ${target}:${remoteDir}.tar.gz`);
    await runOk(SCP, [...sshBase(server), '-P', String(server.port), bundle.archive, `${target}:${remoteDir}.tar.gz`], stream);

    const sudo = server.user === 'root' ? '' : 'sudo -n ';
    const args = [domain && `--domain ${domain}`, email && `--email ${email}`].filter(Boolean).join(' ');
    const cmd = `set -e; mkdir -p ${remoteDir}; tar -xzf ${remoteDir}.tar.gz -C ${remoteDir}; ${sudo}bash ${remoteDir}/provision.sh ${args}; rm -rf ${remoteDir} ${remoteDir}.tar.gz`;
    ctx.log('Running provision.sh on the server');
    await runOk(SSH, [...sshBase(server), '-p', String(server.port), target, cmd], stream);

    const url = `${email ? 'https' : 'http'}://${domain || server.host}/`;
    ctx.log(`Deployed: ${url}`);
    return { url };
  });
}
