// php.ini derived from the distribution's php.ini-development with dev-friendly limits.
// On macOS/Linux the package's own extension setup (conf.d) is left alone; only limits and paths change.
export function writePhpIni(branch) {
  const st = getState();
  const dir = st.components.php[branch].path;
  const base = phpIniBase(branch);
  let ini = base ? fs.readFileSync(base, 'utf8') : '[PHP]\n';
  const vendorBuild = !st.components.php[branch].bins;

  const set = (key, value) => {
    const re = new RegExp(`^;?\\s*${key.replace(/\./g, '\\.')}\\s*=.*$`, 'm');
    const line = `${key} = ${value}`;
    ini = re.test(ini) ? ini.replace(re, line) : `${ini}\n${line}`;
  };
  const ext = (name) => {
    if (!fs.existsSync(path.join(dir, 'ext', `php_${name}.dll`))) return;
    const re = new RegExp(`^;\\s*extension\\s*=\\s*${name}\\s*$`, 'm');
    ini = re.test(ini) ? ini.replace(re, `extension=${name}`) : `${ini}\nextension=${name}`;
  };

  const tz = Intl.DateTimeFormat().resolvedOptions().timeZone || 'UTC';
  const ca = fwd(path.join(P.runtime, 'cacert.pem'));
  if (vendorBuild) {
    set('extension_dir', `"${fwd(path.join(dir, 'ext'))}"`);
    for (const e of ['bz2', 'curl', 'fileinfo', 'gd', 'gettext', 'intl', 'exif', 'mbstring', 'mysqli', 'openssl', 'pdo_mysql', 'pdo_sqlite', 'sqlite3', 'sodium', 'zip', 'xsl']) ext(e);
    if (fs.existsSync(path.join(dir, 'ext', 'php_opcache.dll'))) {
      ini = /^;\s*zend_extension\s*=\s*opcache/m.test(ini)
        ? ini.replace(/^;\s*zend_extension\s*=\s*opcache.*$/m, 'zend_extension=opcache')
        : `${ini}\nzend_extension=opcache`;
    }
  }
  set('memory_limit', '512M');
  set('upload_max_filesize', '256M');
  set('post_max_size', '256M');
  set('max_execution_time', '300');
  set('max_input_vars', '5000');
  set('date.timezone', tz);
  set('error_log', `"${fwd(path.join(P.logs, `php-${branch}.log`))}"`);
  set('session.save_path', `"${fwd(path.join(P.tmp, 'sessions'))}"`);
  set('upload_tmp_dir', `"${fwd(path.join(P.tmp, 'uploads'))}"`);
  set('sys_temp_dir', `"${fwd(P.tmp)}"`);
  set('opcache.enable', '1');
  set('opcache.validate_timestamps', '1');
  set('opcache.revalidate_freq', '0');
  set('cgi.fix_pathinfo', '0');
  set('expose_php', 'Off');
  if (fs.existsSync(path.join(P.runtime, 'cacert.pem'))) {
    set('curl.cainfo', `"${ca}"`);
    set('openssl.cafile', `"${ca}"`);
  }
  const outDir = path.join(P.conf, 'php', branch);
  fs.mkdirSync(outDir, { recursive: true });
  const out = path.join(outDir, 'php.ini');
  fs.writeFileSync(out, ini);
  return out;
}

// php-fpm pool for macOS/Linux: one master on the branch's port, workers sized from the PHP workers setting.
export function writeFpmConf(branch) {
  const pool = getState().settings.phpPoolSize;
  const outDir = path.join(P.conf, 'php', branch);
  fs.mkdirSync(outDir, { recursive: true });
  const file = path.join(outDir, 'php-fpm.conf');
  fs.writeFileSync(file, `; Generated by LocalVPS
[global]
pid = ${path.join(P.data, `php-fpm-${branch}.pid`)}
error_log = ${path.join(P.logs, `php-${branch}-fpm.log`)}
daemonize = no

[www]
listen = 127.0.0.1:${phpPortBase(branch)}
pm = dynamic
pm.max_children = ${pool * 2}
pm.start_servers = 1
pm.min_spare_servers = 1
pm.max_spare_servers = ${pool}
catch_workers_output = yes
clear_env = no
`);
  return file;
}

// Unix socket paths are limited to ~104 bytes (macOS); fall back to the system temp dir for deep installs.
export function mariadbSocket() {
  const inData = path.join(P.tmp, 'mariadb.sock');
  return inData.length < 100 ? inData : path.join(os.tmpdir(), `localvps-${process.getuid?.() ?? 0}-mariadb.sock`);
}

export function writeMyIni() {
  const st = getState();
  const port = st.settings.mariadbPort;
  const bind = st.settings.lan ? '0.0.0.0' : '127.0.0.1';
  const dir = path.join(P.conf, 'mariadb');
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, 'my.ini');
  fs.writeFileSync(file, `# Generated by LocalVPS
[mysqld]
datadir="${fwd(P.mariadbData)}"
port=${port}
bind-address=${bind}
character-set-server=utf8mb4
collation-server=utf8mb4_unicode_ci
max_allowed_packet=256M
innodb_buffer_pool_size=256M
log-error="${fwd(path.join(P.logs, 'mariadb.err'))}"
skip-name-resolve
${IS_WIN ? '' : `socket=${mariadbSocket()}\npid-file=${path.join(P.data, 'mariadb.pid')}\n`}
[client]
port=${port}
default-character-set=utf8mb4
${IS_WIN ? '' : `socket=${mariadbSocket()}\n`}`);
  return file;
}
