import { nginxConfDir, phpIniBase, phpUsesFpm } from './bins.js';

export const phpPortBase = (branch) => {
  const [maj, min] = branch.split('.').map(Number);
  return 9000 + maj * 100 + min * 10;
};

export const upstreamName = (branch) => `php${branch.replace('.', '')}`;

export function siteUrl(name) {
  const port = getState().settings.httpPort;
  return `http://${name}.localhost${port === 80 ? '' : `:${port}`}/`;
}

export const siteRoot = (site) => path.join(P.www, site.name);
export const siteWebroot = (site) => path.join(P.www, site.name, site.webroot || 'public');

function listenLines() {
  const { httpPort, lan, ipv6 } = getState().settings;
  if (lan) return [`listen ${httpPort};`, ...(ipv6 ? [`listen [::]:${httpPort};`] : [])];
  return [`listen 127.0.0.1:${httpPort};`, ...(ipv6 ? [`listen [::1]:${httpPort};`] : [])];
}

function phpLocation(branch, confDir) {
  return `    location ~ \\.php$ {
        try_files $uri =404;
        fastcgi_pass ${upstreamName(branch)};
        fastcgi_index index.php;
        fastcgi_read_timeout 300;
        include "${fwd(path.join(confDir, 'fastcgi_params'))}";
        fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
    }`;
}

function extraBlock(site) {
  return site.extraNginx ? `\n    # --- extra directives ---\n    ${site.extraNginx.split('\n').join('\n    ')}\n` : '';
}

// Node sites: nginx answers *.localhost and proxies to the app's own server (with WebSocket upgrade for HMR).
function renderProxyConf(site, listen, names, logBase) {
  return `# Generated by LocalVPS for Node site "${site.name}" (proxy to 127.0.0.1:${site.appPort}).
server {
    ${listen.join('\n    ')}
    server_name ${names};

    access_log "${logBase}.access.log";
    error_log "${logBase}.error.log";

    location / {
        proxy_pass http://127.0.0.1:${site.appPort};
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $connection_upgrade;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_read_timeout 300;
        proxy_buffering off;
    }
${extraBlock(site)}}
`;
}

export function renderSiteConf(site) {
  const st = getState();
  const confDir = nginxConfDir();
  const listen = listenLines();
  const names = [`${site.name}.localhost`, ...(site.aliases || [])].join(' ');
  const logBase = fwd(path.join(P.logs, 'sites', site.name));
  if (site.type === 'node') return renderProxyConf(site, listen, names, logBase);
  return `# Generated by LocalVPS for site "${site.name}". Put custom directives in the site's Extra nginx field.
server {
    ${listen.join('\n    ')}
    server_name ${names};
    root "${fwd(siteWebroot(site))}";
    index index.php index.html index.htm;
    charset utf-8;

    access_log "${logBase}.access.log";
    error_log "${logBase}.error.log";

    location / {
        try_files $uri $uri/ /index.php?$query_string;
    }

${phpLocation(site.php, confDir)}

    location ~ /\\.(?!well-known) {
        deny all;
    }
${extraBlock(site)}}
`;
}

export function renderNginxConf() {
  const st = getState();
  const confDir = nginxConfDir();
  const pool = st.settings.phpPoolSize;
  const upstreams = Object.keys(st.components.php).map((b) => {
    const base = phpPortBase(b);
    // php-cgi (Windows) is one request per process, so nginx balances across a pool of ports;
    // php-fpm manages its own workers behind a single port.
    const count = phpUsesFpm(b) ? 1 : pool;
    const servers = Array.from({ length: count }, (_, i) => `        server 127.0.0.1:${base + i} max_fails=1 fail_timeout=2s;`).join('\n');
    return `    upstream ${upstreamName(b)} {\n${servers}\n    }`;
  }).join('\n');
  const temp = (name) => `"${fwd(path.join(P.nginxPrefix, 'temp', name))}"`;

  const defaultPhp = st.settings.defaultPhp && st.components.php[st.settings.defaultPhp] ? st.settings.defaultPhp : null;
  return `# Generated by LocalVPS. Changes are overwritten; edit settings in the panel instead.
worker_processes  1;
error_log  "${fwd(path.join(P.logs, 'nginx-error.log'))}";
pid        logs/nginx.pid;

events {
    worker_connections  1024;
}

http {
    include       "${fwd(path.join(confDir, 'mime.types'))}";
    default_type  application/octet-stream;
    sendfile      off;
    keepalive_timeout  65;
    client_max_body_size 256m;
    server_names_hash_bucket_size 128;
    access_log  "${fwd(path.join(P.logs, 'nginx-access.log'))}";
    gzip on;

    # Distro nginx builds default these to /var/lib/nginx, which an unprivileged nginx cannot write.
    client_body_temp_path ${temp('client_body')};
    proxy_temp_path       ${temp('proxy')};
    fastcgi_temp_path     ${temp('fastcgi')};
    uwsgi_temp_path       ${temp('uwsgi')};
    scgi_temp_path        ${temp('scgi')};

    map $http_upgrade $connection_upgrade {
        default upgrade;
        ''      close;
    }

${upstreams}

    # Landing page: http://localhost lists every site
    server {
        ${listenLines().join('\n        ')}
        server_name localhost 127.0.0.1 _;
        root "${fwd(path.join(P.www, '_default'))}";
        index index.html${defaultPhp ? ' index.php' : ''};
${defaultPhp ? phpLocation(defaultPhp, confDir).replace(/^/gm, '    ') : ''}
    }

    include "${fwd(path.join(P.nginxConf, 'sites'))}/*.conf";
}
`;
}

export function writeNginxConfig() {
  const st = getState();
  if (!st.components.nginx) return null;
  const sitesDir = path.join(P.nginxConf, 'sites');
  fs.mkdirSync(sitesDir, { recursive: true });
  for (const f of fs.readdirSync(sitesDir)) fs.rmSync(path.join(sitesDir, f));
  for (const site of st.sites) {
    if (site.enabled === false) continue;
    if (site.type !== 'node' && !st.components.php[site.php]) continue;
    fs.writeFileSync(path.join(sitesDir, `${site.name}.conf`), renderSiteConf(site));
  }
  writeLandingPage();
  const conf = path.join(P.nginxConf, 'nginx.conf');
  fs.writeFileSync(conf, renderNginxConf());
  return conf;
}

